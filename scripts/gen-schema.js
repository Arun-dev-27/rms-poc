/**
 * Reads dbo.Mumin_Mast's column list from the READ-ONLY stage DB and generates:
 *   - src/mumin/mumin.columns.ts   (column metadata used by repository / cache / validation)
 *   - docker/mssql/init.sql        (mirror table DDL + change tracking for the docker MSSQL)
 * Usage: node scripts/gen-schema.js
 */
const path = require('path');
const fs = require('fs');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const sql = require('mssql');

const TABLE = 'Mumin_Mast';
const KEY = 'Mumin_ID';

(async () => {
  const pool = await new sql.ConnectionPool({
    server: process.env.SOURCE_MSSQL_HOST,
    port: Number(process.env.SOURCE_MSSQL_PORT || 1433),
    user: process.env.SOURCE_MSSQL_USER,
    password: process.env.SOURCE_MSSQL_PASSWORD,
    database: process.env.SOURCE_MSSQL_DATABASE,
    options: { encrypt: false, trustServerCertificate: true },
  }).connect();
  const cols = (await pool.request().input('t', TABLE).query(`
    SELECT COLUMN_NAME name, DATA_TYPE type, CHARACTER_MAXIMUM_LENGTH len,
           NUMERIC_PRECISION prec, NUMERIC_SCALE scale, IS_NULLABLE nullable
    FROM INFORMATION_SCHEMA.COLUMNS
    WHERE TABLE_SCHEMA = 'dbo' AND TABLE_NAME = @t ORDER BY ORDINAL_POSITION`)).recordset;
  await pool.close();

  const sqlType = (c) =>
    c.type === 'varchar' || c.type === 'nvarchar' ? `${c.type.toUpperCase()}(${c.len === -1 ? 'MAX' : c.len})`
    : c.type === 'numeric' || c.type === 'decimal' ? `${c.type.toUpperCase()}(${c.prec},${c.scale})`
    : c.type.toUpperCase();

  const meta = cols.map((c) => ({
    name: c.name, type: c.type, sql: sqlType(c), length: c.len ?? undefined,
    precision: c.type === 'numeric' ? c.prec : undefined, scale: c.type === 'numeric' ? c.scale : undefined,
    nullable: c.nullable === 'YES',
  }));

  const ts = `// AUTO-GENERATED by scripts/gen-schema.js from stage MMS.dbo.${TABLE}. Do not edit by hand.
export type ColumnType = 'int' | 'numeric' | 'varchar' | 'nvarchar' | 'datetime' | 'bit';

export interface ColumnMeta {
  name: string;
  type: ColumnType;
  sql: string;
  length?: number;
  precision?: number;
  scale?: number;
  nullable: boolean;
}

export const TABLE = 'dbo.${TABLE}';
export const KEY_COLUMN = '${KEY}';

export const COLUMNS: ColumnMeta[] = ${JSON.stringify(meta, null, 2).replace(/"(\w+)":/g, '$1:').replace(/"/g, "'")};
`;
  fs.writeFileSync(path.join(__dirname, '..', 'src', 'mumin', 'mumin.columns.ts'), ts);

  const ddl = cols.map((c) => `    [${c.name}] ${sqlType(c)} ${c.nullable === 'YES' ? 'NULL' : 'NOT NULL'}`).join(',\n');
  const init = `-- AUTO-GENERATED by scripts/gen-schema.js. Mirror of stage MMS.dbo.${TABLE} (docker only).
IF DB_ID('MMS') IS NULL CREATE DATABASE MMS;
GO
-- Change Tracking = how Redis catches up after a snapshot restore (updates, inserts AND deletes)
IF NOT EXISTS (SELECT 1 FROM sys.change_tracking_databases WHERE database_id = DB_ID('MMS'))
  ALTER DATABASE MMS SET CHANGE_TRACKING = ON (CHANGE_RETENTION = 7 DAYS, AUTO_CLEANUP = ON);
GO
USE MMS;
GO
IF OBJECT_ID('dbo.${TABLE}', 'U') IS NULL
BEGIN
  CREATE TABLE dbo.${TABLE} (
${ddl},
    CONSTRAINT PK_${TABLE} PRIMARY KEY CLUSTERED ([${KEY}])
  );
  ALTER TABLE dbo.${TABLE} ENABLE CHANGE_TRACKING WITH (TRACK_COLUMNS_UPDATED = OFF);
END
GO
`;
  fs.writeFileSync(path.join(__dirname, '..', 'docker', 'mssql', 'init.sql'), init);
  console.log(`Generated ${meta.length} columns`);
})().catch((e) => { console.error(e.message); process.exit(1); });
